"""Time the queries the product depends on, on the real graph, and write docs/benchmarks.md.

Times are FalkorDB's own server-side execution time ("Query internal execution time"), so they exclude
network and Python. Each query runs 3 times to warm up, then 25 times; we report the median and p95.
Three headline queries also get their GRAPH.PROFILE plan (operators, records produced, time per operator).

    uv run python -m scripts.bench_queries
"""

import asyncio
import platform
import statistics
from datetime import date, timedelta
from pathlib import Path

from lineage.db import get_db, ro
from lineage.graph import queries as Q
from lineage.graph.udf import ensure_udfs

COMPANY, AGENT = "lineage:company", "lineage:agent:historian"
WARMUP, RUNS = 3, 25


def cases(vec: list[float]) -> list[tuple[str, str, str, str, dict]]:
    today = date.today()
    return [
        # (what it does for the product, query name, graph, cypher, params)
        ("Semantic search over PEP passages (vector index, k=12)", "VECTOR_CHUNKS", COMPANY, Q.VECTOR_CHUNKS, {"k": 12, "q": vec, "as_of": None}),
        ("Keyword search over PEP titles (full-text index)", "FULLTEXT_PEP_TITLES", COMPANY, Q.FULLTEXT_PEP_TITLES, {"q": "annotations", "k": 12, "as_of": None}),
        ("Who decided PEP 649, and where it was announced", "DECISION_PROVENANCE", COMPANY, Q.DECISION_PROVENANCE, {"id": "pep:649"}),
        ("PEP 563's supersede chain, both directions, up to 3 hops", "SUPERSEDE_CHAIN", COMPANY, Q.SUPERSEDE_CHAIN, {"id": "pep:563"}),
        ("Proposals within 2 citation hops of PEP 484", "RELATED_2", COMPANY, Q.RELATED_2, {"id": "pep:484"}),
        ("Listed and actual owners of asyncio", "AREA_EXPERTS", COMPANY, Q.AREA_EXPERTS, {"id": "area:asyncio"}),
        ("The ripple: everything that cites PEP 563", "RIPPLE_SOFT_1", COMPANY, Q.RIPPLE_SOFT_1, {"changed": ["pep:563"], "exclude": []}),
        ("Recency-weighted knowledge for every module (JavaScript UDF)", "AREA_RECENCY", COMPANY, Q.AREA_RECENCY,
         {"areas": None, "as_of": today.isoformat(), "half_life": 180, "since": (today - timedelta(days=365)).isoformat()}),
        ("Introduction path through collaboration ties (algo.SPpaths)", "INTRO_PATH", COMPANY, Q.INTRO_PATH,
         {"src": "person:kumaraditya303", "dst": "person:jellezijlstra"}),
        ("Bridge people: betweenness over all contributors (algo.betweenness)", "BETWEENNESS_PEOPLE", COMPANY, Q.BETWEENNESS_PEOPLE, {}),
        ("Topic clusters over the citation graph (algo.labelPropagation)", "PEP_COMMUNITIES", COMPANY, Q.PEP_COMMUNITIES, {"min": 3}),
        ("What in the agent's memory rests on PEP 563 (DERIVED_FROM walk)", "DEPENDENTS_PREVIEW", AGENT, Q.DEPENDENTS_PREVIEW, {"refs": ["pep:563"]}),
    ]


async def time_query(g, cypher: str, params: dict) -> tuple[float, float, int]:
    for _ in range(WARMUP):
        await g.ro_query(cypher, params)
    times, rows = [], 0
    for _ in range(RUNS):
        r = await g.ro_query(cypher, params)
        times.append(r.run_time_ms)
        rows = len(r.result_set)
    times.sort()
    return statistics.median(times), times[int(0.95 * (len(times) - 1))], rows


async def main():
    from lineage.ingest.embed import Embedder

    vec = Embedder().embed(["deferred evaluation of annotations"])[0]
    db = await get_db()
    await ensure_udfs(db)
    info = await db.connection.execute_command("INFO", "server")
    redis_version = next((l.split(":")[1] for l in info.decode().splitlines() if l.startswith("redis_version")), "?") \
        if isinstance(info, bytes) else info.get("redis_version", "?")
    company = db.select_graph(COMPANY)
    sizes = (await ro(company, "MATCH (n) WITH count(n) AS nodes MATCH ()-[r]->() RETURN nodes, count(r) AS edges"))[0]

    rows = []
    for what, name, graph, cypher, params in cases(vec):
        med, p95, n = await time_query(db.select_graph(graph), cypher, params)
        rows.append((what, name, med, p95, n))
        print(f"{name:22} median {med:7.2f} ms  p95 {p95:7.2f} ms  rows {n}")

    plans = []
    for what, name, graph, cypher, params in [c for c in cases(vec) if c[1] in ("RIPPLE_SOFT_1", "INTRO_PATH", "VECTOR_CHUNKS")]:
        plan = await db.select_graph(graph).profile(cypher, params)
        plans.append((what, name, str(plan)))

    out = [
        "# Query benchmarks",
        "",
        "Generated by `uv run python -m scripts.bench_queries` on "
        f"{date.today().isoformat()}. FalkorDB 6.0.2 on Redis {redis_version}, Docker on {platform.system()} {platform.machine()}.",
        f"The company graph has **{sizes['nodes']:,} nodes and {sizes['edges']:,} relationships**.",
        "",
        f"Times are FalkorDB's server-side execution time (no network, no Python): {WARMUP} warm-up runs, then {RUNS} timed runs.",
        "FalkorDB caches a query's plan after its first run, so these are steady-state times. Result sets are not cached.",
        "`DEPENDENTS_PREVIEW` walks the Historian's memory, which holds little right after a demo reset, so its time is a floor.",
        "",
        "| What it does for the product | Query | Median | p95 | Rows |",
        "|---|---|---:|---:|---:|",
        *[f"| {w} | `{n}` | {m:.2f} ms | {p:.2f} ms | {r} |" for w, n, m, p, r in rows],
        "",
        "All queries live in [`lineage/graph/queries.py`](../lineage/graph/queries.py) and are listed in [queries.md](queries.md).",
        "",
        "## Plans (GRAPH.PROFILE)",
        "",
    ]
    for what, name, plan in plans:
        out += [f"### `{name}`: {what}", "", "```", plan.strip(), "```", ""]
    Path("docs/benchmarks.md").write_text("\n".join(out))
    print("wrote docs/benchmarks.md")
    await db.aclose()


if __name__ == "__main__":
    asyncio.run(main())
